package io.github.niravgrowlity.quotewidget

import android.content.Context
import android.content.SharedPreferences
import org.json.JSONArray
import org.json.JSONObject
import kotlin.random.Random

/** A quote. [collection] is the id of the collection it belongs to. */
data class Quote(val id: Long, val text: String, val pinned: Boolean, val collection: Long = QuoteStore.DEFAULT_COLLECTION)

data class QuoteCollection(val id: Long, val name: String)

/** The order the widget goes through the quotes in. */
enum class CycleOrder(val label: String, val description: String) {
    MY_ORDER("My order", "In the order you arrange them. Use Reorder on the Quotes tab."),
    SHUFFLE("Shuffle", "A new random order each time it has shown them all."),
    NEWEST("Newest first", "Most recently added first."),
    OLDEST("Oldest first", "In the order you added them."),
    A_Z("A–Z", "Alphabetically."),
}

/** Light/dark for the app and the widget. Order matters: it indexes WidgetStyle's layouts. */
enum class ThemeMode(val label: String) { SYSTEM("System"), LIGHT("Light"), DARK("Dark") }

// WidgetStyle is generated by tools/gen_widget_res.py (WidgetStyle.kt).

/**
 * Splits a quote into its text and author, so the widget can show the author on its own line.
 * Recognises a last line starting with a dash ("…\n— Seneca") or a trailing " — Seneca".
 */
object QuoteFormat {
    private val authorLine = Regex("""\n\s*[—–~-]+\s*([^\n]{1,60})\s*$""")
    private val inlineAuthor = Regex("""\s[—–]\s*([^—–\n]{2,60})$""")
    private val quoteChars = charArrayOf('"', '“', '”', '„', '«', '»')

    fun split(raw: String): Pair<String, String?> {
        val t = raw.trim()
        val m = authorLine.find(t) ?: inlineAuthor.find(t)
        val body = (if (m != null) t.substring(0, m.range.first) else t)
            .trim().trimStart(*quoteChars).trimEnd(*quoteChars).trim()
        if (body.isEmpty()) return t to null
        return body to m?.groupValues?.get(1)?.trim()?.ifEmpty { null }
    }
}

/** Upper limit for the auto-fitted text; long quotes shrink below it to fit. */
enum class TextSize(val label: String, val scale: Float) {
    SMALL("S", 0.75f), MEDIUM("M", 1f), LARGE("L", 1.3f), XL("XL", 1.6f),
}

enum class Align(val label: String) { START("Left"), CENTER("Center") }

/**
